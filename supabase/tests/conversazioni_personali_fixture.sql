CREATE TABLE public.messaggi(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mittente_id uuid NOT NULL REFERENCES auth.users(id),
  destinatario_id uuid NOT NULL REFERENCES auth.users(id),
  testo text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  letto_at timestamptz
);
ALTER TABLE public.messaggi ENABLE ROW LEVEL SECURITY;
CREATE POLICY fixture_leggi ON public.messaggi FOR SELECT TO authenticated
  USING (auth.uid() IN (mittente_id, destinatario_id));
CREATE POLICY fixture_invia ON public.messaggi FOR INSERT TO authenticated
  WITH CHECK (mittente_id = auth.uid());
GRANT SELECT, INSERT ON public.messaggi TO authenticated;
GRANT USAGE ON SEQUENCE public.messaggi_id_seq TO authenticated;
